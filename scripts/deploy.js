import hre from "hardhat";
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const { ethers } = hre;
const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

async function main() {
  console.log("==================================================");
  console.log("       Deploying FundChain Crowdfunding Contract   ");
  console.log("==================================================");

  const [deployer] = await ethers.getSigners();
  console.log("Deploying with account:", deployer.address);

  const balance = await ethers.provider.getBalance(deployer.address);
  console.log("Account balance:", ethers.formatEther(balance), "ETH");

  const Crowdfunding = await ethers.getContractFactory("Crowdfunding");
  const crowdfunding = await Crowdfunding.deploy();
  await crowdfunding.waitForDeployment();

  const contractAddress = await crowdfunding.getAddress();
  console.log("--------------------------------------------------");
  console.log(">> Crowdfunding deployed successfully to:", contractAddress);
  console.log("--------------------------------------------------");

  // Export contract address & ABI to frontend automatically
  const frontendDir = path.join(__dirname, "..", "frontend", "src", "blockchain");
  if (!fs.existsSync(frontendDir)) {
    fs.mkdirSync(frontendDir, { recursive: true });
  }

  const contractArtifact = await hre.artifacts.readArtifact("Crowdfunding");

  // Save ABI
  fs.writeFileSync(
    path.join(frontendDir, "CrowdfundingABI.json"),
    JSON.stringify(contractArtifact.abi, null, 2)
  );
  console.log("Saved ABI to frontend/src/blockchain/CrowdfundingABI.json");

  // Save Config
  const network = await ethers.provider.getNetwork();
  const configContent = `// Automatically generated by scripts/deploy.js
export const CONTRACT_ADDRESS = "${contractAddress}";
export const ADMIN_ADDRESS = "${deployer.address}";
export const CHAIN_ID = ${network.chainId.toString()};
export const NETWORK_NAME = "${network.name === "unknown" ? "localhost" : network.name}";

export const SUPPORTED_NETWORKS = {
  31337: {
    chainIdHex: "0x7a69",
    chainIdDec: 31337,
    name: "Localhost 8545 (Hardhat)",
    rpcUrl: "http://127.0.0.1:8545",
    currencySymbol: "ETH",
    blockExplorer: null,
  },
  11155111: {
    chainIdHex: "0xaa36a7",
    chainIdDec: 11155111,
    name: "Sepolia Testnet",
    rpcUrl: "https://rpc.sepolia.org",
    currencySymbol: "SepoliaETH",
    blockExplorer: "https://sepolia.etherscan.io",
  },
};
`;
  fs.writeFileSync(path.join(frontendDir, "config.js"), configContent);
  console.log("Saved configuration to frontend/src/blockchain/config.js");

  console.log("Deployment complete!");
}

main()
  .then(() => process.exit(0))
  .catch((error) => {
    console.error(error);
    process.exit(1);
  });
